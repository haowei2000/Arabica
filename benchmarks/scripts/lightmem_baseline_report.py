"""Export and verify the LightMem/MemBase reference baseline table.

Examples:
    python -m benchmarks.scripts.lightmem_baseline_report --format markdown
    python -m benchmarks.scripts.lightmem_baseline_report --format latex \
        --output paper/tables/lightmem_locomo_baselines.tex
    python -m benchmarks.scripts.lightmem_baseline_report \
        --check-paper-table paper/tables/lightmem_locomo_baselines.tex
"""

from __future__ import annotations

import argparse
from collections.abc import Iterable
import csv
import io
import json
from pathlib import Path

from benchmarks.baselines.lightmem_reference import (
    LIGHTMEM_README_URL,
    LightMemLoCoMoOverview,
    iter_locomo_overview,
    locomo_overview_dicts,
)

DEFAULT_BACKBONE = "gpt-4o-mini"


def _format_float(value: float | None, *, digits: int = 2) -> str:
    if value is None:
        return "-"
    return f"{value:.{digits}f}"


def _format_markdown_float(value: float | None, *, digits: int = 3) -> str:
    if value is None:
        return "-"
    return f"{value:,.{digits}f}"


def _format_int(value: int | None) -> str:
    if value is None:
        return "-"
    return f"{value:,}"


def _format_tex_number(value: float | int | None, *, digits: int = 1) -> str:
    if value is None:
        return "--"
    text = f"{value:,}" if isinstance(value, int) else f"{value:,.{digits}f}"
    return text.replace(",", "{,}")


def _latex_url(value: str) -> str:
    return value.replace("#", r"\#")


def render_json(rows: Iterable[LightMemLoCoMoOverview]) -> str:
    return json.dumps([row.to_dict() for row in rows], indent=2, sort_keys=True)


def render_csv(rows: Iterable[LightMemLoCoMoOverview]) -> str:
    output = io.StringIO()
    fieldnames = list(locomo_overview_dicts(backbone=DEFAULT_BACKBONE)[0].keys())
    writer = csv.DictWriter(output, fieldnames=fieldnames)
    writer.writeheader()
    for row in rows:
        writer.writerow(row.to_dict())
    return output.getvalue()


def render_markdown(rows: Iterable[LightMemLoCoMoOverview]) -> str:
    lines = [
        "| Method | Acc. GPT judge | Acc. Qwen judge | Memory tokens (k) | QA tokens (k) | Total tokens (k) | Calls | Runtime (s) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in rows:
        lines.append(
            "| "
            + " | ".join(
                [
                    row.method,
                    _format_float(row.accuracy_gpt4o_judge),
                    _format_float(row.accuracy_qwen_judge),
                    _format_markdown_float(row.memory_construction_tokens_k),
                    _format_markdown_float(row.qa_tokens_k),
                    _format_markdown_float(row.total_tokens_k),
                    _format_int(row.calls),
                    _format_int(row.runtime_seconds),
                ]
            )
            + " |"
        )
    return "\n".join(lines)


def render_latex(rows: Iterable[LightMemLoCoMoOverview]) -> str:
    body = []
    for row in rows:
        body.append(
            "        "
            + " & ".join(
                [
                    row.method,
                    f"{row.accuracy_gpt4o_judge:.2f}",
                    f"{row.accuracy_qwen_judge:.2f}",
                    _format_tex_number(row.memory_construction_tokens_k),
                    _format_tex_number(row.qa_tokens_k),
                    _format_tex_number(row.total_tokens_k),
                    _format_tex_number(row.runtime_seconds, digits=0),
                ]
            )
            + r" \\"
        )
    body_text = "\n".join(body)
    source_url = _latex_url(LIGHTMEM_README_URL)
    return (
        "% Generated by: python -m benchmarks.scripts.lightmem_baseline_report --format latex\n"
        "\\begin{table}[t]\n"
        "    \\centering\n"
        "    \\scriptsize\n"
        "    \\resizebox{\\linewidth}{!}{%\n"
        "    \\begin{tabular}{lrrrrrr}\n"
        "        \\toprule\n"
        "        Method & GPT judge & Qwen judge & Mem. Tok. & QA Tok. & Total Tok. & Runtime \\\\\n"
        "        \\midrule\n"
        f"{body_text}\n"
        "        \\bottomrule\n"
        "    \\end{tabular}\n"
        "    }\n"
        "    \\caption{External LoCoMo baseline data reported by "
        "LightMem/MemBase for a GPT-4o-mini backbone. Accuracy columns "
        "are percentages under GPT-4o-mini and Qwen2.5-32B judges. "
        "Token columns are in thousands. These rows are reference "
        "baselines for our evaluation plan, not new \\textsc{Structure} "
        f"measurements. Source: \\citet{{fang2026lightmem}} and \\url{{{source_url}}}.}}\n"
        "    \\label{tab:lightmem-locomo-baselines}\n"
        "\\end{table}\n"
    )


def render_report(
    rows: Iterable[LightMemLoCoMoOverview],
    *,
    output_format: str,
) -> str:
    rows = list(rows)
    if output_format == "json":
        return render_json(rows)
    if output_format == "csv":
        return render_csv(rows)
    if output_format == "markdown":
        return render_markdown(rows)
    if output_format == "latex":
        return render_latex(rows)
    raise ValueError(f"unsupported format: {output_format}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Export LightMem/MemBase reference baseline data.",
    )
    parser.add_argument(
        "--backbone",
        default=DEFAULT_BACKBONE,
        help="Backbone model to include in the report.",
    )
    parser.add_argument(
        "--format",
        choices=("json", "csv", "markdown", "latex"),
        default="markdown",
        help="Report format.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        help="Write the rendered report to this path instead of stdout.",
    )
    parser.add_argument(
        "--check-paper-table",
        type=Path,
        help="Exit non-zero unless this paper table exactly matches the rendered LaTeX.",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    rows = list(iter_locomo_overview(backbone=args.backbone))
    if not rows:
        raise SystemExit(f"no LightMem LoCoMo rows for backbone {args.backbone!r}")

    rendered = render_report(rows, output_format=args.format)

    if args.check_paper_table is not None:
        expected = render_report(rows, output_format="latex")
        actual = args.check_paper_table.read_text(encoding="utf-8")
        if actual != expected:
            raise SystemExit(
                f"{args.check_paper_table} is out of sync with LightMem baseline data"
            )

    if args.output is not None:
        args.output.write_text(rendered, encoding="utf-8")
    else:
        print(rendered)
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
